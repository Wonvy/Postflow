const messages: Record<Lang, Record<MessageKey, string>> = { zh, en };

/** 内置语言的全部文字，导出语言文件时用。 */
export function builtinMessages(lang: Lang): Record<MessageKey, string> {
  return messages[lang];
}

/** 正在用的导入语言；用内置语言时为 null。 */
export function activePack(pref: LangPref): LangPack | null {
  return findPack(packCodeOf(pref));
}

/**
 * 日期、数字、排序这些按哪种内置语言来。导入的语言按它文件里写的 `base`；
 * 导入的语言被删了的话退回跟随系统。
 */
export function resolveLang(pref: LangPref): Lang {
  const code = packCodeOf(pref);
  if (code) return findPack(code)?.base ?? resolveLang("system");
  if (pref !== "system") return pref as Lang;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function translate(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
  pack?: LangPack | null,
): string {
  let text: string = pack?.messages[key] ?? messages[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function useLang(): Lang {
  const pref = useUi((s) => s.lang);
  // 导入的语言变了（重新导入、删除）也要重新算
  useLangPacks((s) => s.packs);
  return resolveLang(pref);
}

export function useT(): Translate {
  const pref = useUi((s) => s.lang);
  const packs = useLangPacks((s) => s.packs);
  const lang = resolveLang(pref);
  const code = packCodeOf(pref);
  const pack = code ? (packs.find((p) => p.code === code) ?? null) : null;
  return useCallback((key, vars) => translate(lang, key, vars, pack), [lang, pack]);
}

/**
 * AI 服务自己回的原话（比如「余额不足」），只有这几种错误才有；别的 AI 错误带的是 Postflow 自己写给开发者看的英文，
 * 不给用户看（写在日志里）。
 */
const AI_SERVICE_SAID = new Set([
  "ai_auth",
  "ai_balance",
  "ai_rate_limited",
  "ai_model_not_found",
  "ai_too_long",
  "ai_region",
  "ai_server",
]);

/** 邮件服务器、AI 服务自己给出的原因。通用提示之外再给用户看，常常直接说明了问题在哪。 */
export function errorDetail(err: unknown): string | null {
  if (!err || typeof err !== "object" || !("code" in err) || !("message" in err)) return null;
  const code = String(err.code);
  const message = String(err.message ?? "").trim();
  if (!message) return null;
  if (code.startsWith("ai_")) return AI_SERVICE_SAID.has(code) ? message : null;
  return code.startsWith("mail_") || code.startsWith("send_") ? message : null;
}

/** 把核心返回的错误码换成给人看的话。 */
export function errorText(t: Translate, err: unknown): string {
  const code =
    err instanceof RpcError
      ? err.code
      : err && typeof err === "object" && "code" in err
        ? String(err.code)
        : "unknown";
  const key = `error.${code}` as MessageKey;
  return key in zh ? t(key) : t("error.unknown");
}
